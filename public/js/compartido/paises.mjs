const POR_CODIGO = new Map(PAISES.map(p => [p.codigo, p]));

export function nombrePais(codigo) {
  const c = String(codigo || '').trim().toUpperCase();
  return POR_CODIGO.get(c)?.nombre || c;
}

export function iso3DeIso2(iso2) {
  const c = String(iso2 || '').trim().toUpperCase();
  const p = PAISES.find(x => x.iso2 === c);
  return p ? p.codigo : '';
}

// Argentina primero (es el default de la ficha). El resto, por nombre.
export function opcionesPais({ vacio } = {}) {
  const arg = PAISES.find(p => p.codigo === 'ARG');
  const resto = PAISES.filter(p => p.codigo !== 'ARG')
    .slice()
    .sort((a, b) => a.nombre.localeCompare(b.nombre, 'es'));
  const opciones = [arg, ...resto].map(p => ({ value: p.codigo, label: p.nombre + ' (' + p.codigo + ')' }));
  if (vacio) opciones.unshift({ value: '', label: vacio });
  return opciones;
}
